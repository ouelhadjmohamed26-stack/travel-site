function setLanguage(lang){
  document.documentElement.lang = lang === 'ar' ? 'ar' : (lang === 'fr' ? 'fr' : 'en');
  if(lang === 'ar') document.documentElement.setAttribute('dir','rtl');
  else document.documentElement.setAttribute('dir','ltr');

  document.querySelectorAll('[data-key]').forEach(el=>{
    const key = el.getAttribute('data-key');
    if(translations[lang] && translations[lang][key]) el.textContent = translations[lang][key];
  });

  document.querySelectorAll('[data-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-placeholder');
    if(translations[lang] && translations[lang][key]) el.placeholder = translations[lang][key];
  });
}

// Attach events
['en','fr','ar'].forEach(lang => {
  const btn = document.getElementById('lang-' + lang);
  if(btn){
    btn.addEventListener('click', ()=>{
      setLanguage(lang);
      document.querySelectorAll('.lang-btn').forEach(b=>b.classList.remove('active'));
      btn.classList.add('active');
      // close mobile menu after selection
      document.body.classList.remove('menu-open');
    });
  }
});

// Mobile menu toggle
const menuToggle = document.getElementById('menu-toggle');
if(menuToggle){
  menuToggle.addEventListener('click', ()=>{
    document.body.classList.toggle('menu-open');
  });
}

// Close mobile menu when clicking a nav link
document.querySelectorAll('.nav-link').forEach(n=>{
  n.addEventListener('click', ()=> document.body.classList.remove('menu-open'));
});

const bookingForm = document.getElementById('booking-form');
if(bookingForm){
  bookingForm.addEventListener('submit', event => {
    event.preventDefault();
    const messageEl = document.getElementById('booking-thanks');
    const lang = document.documentElement.lang || 'fr';
    const text = translations[lang]?.formThanks || translations.fr.formThanks;
    messageEl.textContent = text;
    event.target.reset();
  });
}

